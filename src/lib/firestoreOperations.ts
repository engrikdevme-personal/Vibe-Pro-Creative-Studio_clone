/**
 * ✅ BATCH UPDATE FOR COMPLEX SCENARIOS
 * If multiple updates need to be atomic, use batch
 * Firestore batches up to 500 operations
 * 
 * @param userId - Current user's ID
 * @param sessionId - Session to update
 * @param updates - Fields to update
 * @param batch - Pre-initialized WriteBatch
 */
export async function batchUpdateSession(
  userId: string,
  sessionId: string,
  updates: Record<string, any>,
  batch: WriteBatch
) {
  try {
    const sessionRef = doc(db, `users/${userId}/sessions`, sessionId);
    
    batch.update(sessionRef, {
      ...updates,
      lastUpdated: serverTimestamp()
    });
    
    // Don't commit here - let caller manage batch lifecycle
    // await batch.commit();
  } catch (error) {
    handleFirestoreError(
      error,
      OperationType.UPDATE,
      `users/${userId}/sessions/${sessionId}`
    );
  }
}

